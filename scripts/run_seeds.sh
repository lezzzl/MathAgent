#!/usr/bin/env bash
# Гоняет команду бенчмарков (всё, что передано скрипту) по разу на каждый сид.
#
# Нужен потому, что спека диспетчера исполняется без shell: цикл `for SEED in ...`
# прямо в `command:` не заработает. Здесь же цикл оказывается ВНУТРИ команды
# бенчмарков, то есть внутри run_benchmarks*.sh, — сервера поднимаются один раз
# на все сиды, а не по разу на каждый (для 35B это десятки минут разницы).
#
# --seed и --run-id дописывает скрипт, в вызове их быть не должно. {SEED} в
# шаблоне обязателен: без него каталоги прогонов совпали бы и следующий сид
# писал бы поверх предыдущего. Сиды и шаблон меняются правкой этих двух строк.
#
# Первый упавший сид останавливает прогон (set -e): обычно это OOM или
# недоступный сервер, и оставшиеся сиды всё равно уткнутся в то же самое.
set -euo pipefail

SEEDS="43 44 45"
RUN_ID_TEMPLATE="qwen35-9b-react-v8-repair-imo-seed{SEED}-v2"

for seed in ${SEEDS}; do
  run_id="${RUN_ID_TEMPLATE//\{SEED\}/${seed}}"
  echo ">>> seed=${seed}, run_id=${run_id}"
  "$@" --seed "${seed}" --run-id "${run_id}"
done
